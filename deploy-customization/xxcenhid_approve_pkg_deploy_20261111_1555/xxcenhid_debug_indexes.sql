SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
  PROCEDURE run(stmt VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE stmt;
    DBMS_OUTPUT.PUT_LINE('created: ' || SUBSTR(stmt, 1, 200));
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE IN (-955, -1408) THEN DBMS_OUTPUT.PUT_LINE('already there: ' || SUBSTR(stmt, 1, 200));
    ELSE RAISE; END IF;
  END;
BEGIN
  run('CREATE UNIQUE INDEX "APPS"."SYS_IL0001007142C00002$$" ON "APPS"."XXCENHID_DEBUG" (');
END;
/
